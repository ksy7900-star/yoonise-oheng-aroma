  function daeunNow(s) {
    var du = s.daeun;
    if (!du || !du.list || !du.list.length || !s.solar || !s.solar.y) return null;
    var age = 2027 - Number(s.solar.y) + 1;
    var cur = null;
    for (var i = 0; i < du.list.length; i++) {
      if (du.list[i].age <= age) cur = du.list[i];
    }
    return cur && cur.ten ? cur : null;
  }

