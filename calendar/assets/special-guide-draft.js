  function seunRelation(s) {
    var se = s.seun || {};
    if (se.chung_day) return 'chung';
    if (se.hap_day) return 'hap';
    if (se.hyeong_day) return 'hyeong';
    return 'none';
  }
  function monthLabel(m) { return m === 1 ? '2028년 1월' : m + '월'; }
  function groupOfTen(t) {
    if (!t) return '';
    if (/비견|겁재/.test(t)) return '비겁';
    if (/식신|상관/.test(t)) return '식상';
    if (/편재|정재/.test(t)) return '재성';
    if (/편관|정관/.test(t)) return '관성';
    if (/편인|정인/.test(t)) return '인성';
    return '';
  }
  function pick(arr, seed) { return arr[Math.abs(seed) % arr.length]; }

  function make(s) {
    if (!s) return '';
    var dm = s.day_master || {};
    var stemKey = dm.gan || '';
    var stem = STEM[stemKey] || STEM['甲'];
    var name = s.name ? s.name + ' 님' : '고객님';
    var counts = s.counts || {};
    var nChar = s.time_known ? 8 : 6;
    var charWord = s.time_known ? '여덟 글자' : '여섯 글자';
    var timeNote = s.time_known ? '' : ' 태어난 시각을 모르고 봤으니, 시주는 빼고 큰 흐름만 읽었습니다.';

    var els = ELS.slice().sort(function (a, b) { return (counts[b] || 0) - (counts[a] || 0); });
    var strongEl = els[0], strongN = counts[strongEl] || 0;
    var weakEl = els[els.length - 1], weakN = counts[weakEl] || 0;
    /* 과다: 8글자에서 3자 이상(6글자는 2자 이상), 부족: 0~1자 */
    var overEl = strongN >= (nChar >= 8 ? 3 : 2) ? strongEl : '';
    var lackEl = weakN <= 1 ? weakEl : '';

    /* ① 영역 — 십성 분포 + 2027 세운 십성에 가산 */
    var g = s.ten_groups || {};
    var seunTen = (s.seun && s.seun.ten) || '';
    var seunGroup = groupOfTen(seunTen);
    var scores = {};
    ['관성', '재성', '식상', '인성', '비겁'].forEach(function (k) {
      scores[k] = (g[k] || 0) * 2 + (k === seunGroup ? 3 : 0);
    });
    var areaKey = '관성', best = -1;
    ['관성', '재성', '식상', '인성', '비겁'].forEach(function (k) {
      if (scores[k] > best) { best = scores[k]; areaKey = k; }
    });
    var area = GROUP[areaKey];
    var sameFlow = areaKey === seunGroup;

    var L = [];
    L.push('『윤이세가 직접 전하는 2027년 맞춤 운세 활용 가이드』');
    L.push('');
    L.push('안녕하세요, 윤이세입니다.');
    L.push(name + '의 사주를 2027년 정미년과 함께 읽었습니다. 일간은 ' +
      (ganKo(stemKey) || '') + '(' + stemKey + ') ' + (dm.element || '') + '이고, ' +
      charWord + ' 가운데 ' + strongEl + '의 결이 ' + strongN + '자로 가장 또렷합니다.' + timeNote);
    L.push('');

    /* ── 1 ───────────────────────────────────────────── */
    L.push('1. 2027년 가장 집중해야 할 인생 영역 1가지');
    L.push('2027년 ' + name + '이 가장 힘을 주면 좋은 자리는 「' + area.area + '」 한 곳입니다.');
    var why = '사주 안에서 ' + areaKey + '의 결이 ' + ((g[areaKey] || 0)) + '자로 잡히고';
    if (sameFlow) {
      why += ', 2027년 정미년의 ' + seunTen + ' 기운이 바로 이 자리로 들어옵니다. 해의 힘이 내 힘과 같은 방향이라, 여기에 시간을 쓰면 남는 것이 큽니다.';
    } else {
      why += ', 2027년 정미년은 ' + (seunTen || '한 해의 기운') + '의 결로 흐릅니다. 해의 흐름을 억지로 거스르지 않고, 내가 이미 가진 힘을 이 자리에 얹는 쪽이 편합니다.';
    }
    L.push(why);
    L.push(area.focus + '.');
    L.push('다만 이 한 곳에만 매달리지 마세요. 나머지는 지금 하던 흐름대로 두면 됩니다.');
    L.push('');

    /* ── 2 ───────────────────────────────────────────── */
    L.push('2. 나에게 기회가 되는 상황과 활용 방법');
    var relKey = seunRelation(s);
    var rel = REL[relKey];
    L.push(rel.lead + '.');
    var du = daeunNow(s);
    if (du && TEN_LIFE[du.ten]) {
      L.push('대운으로 보면 지금은 ' + du.age + '세부터의 ' + (ganKo(du.gan) || du.gan) + (zhiKo(du.zhi) || du.zhi) +
        ' 대운 안입니다. ' + du.ten + '의 결, 곧 ' + TEN_LIFE[du.ten] + '이라 2027년의 선택도 그 바탕 위에서 하게 됩니다.');
    }
    var ten = TEN[seunTen] || TEN['정인'];
    L.push(ten.when + '.');
    L.push('활용법은 이렇습니다. ' + ten.how + '.');
    var months = s.months || [];
    var good = months.filter(function (m) { return m.hap_day; }).map(function (m) { return monthLabel(m.month); });
    var warn = months.filter(function (m) { return m.chung_day; }).map(function (m) { return monthLabel(m.month); });
    if (good.length) L.push(good.join('·') + '에는 먼저 움직이거나 제안하기 좋습니다. 미뤄 둔 일을 꺼내기에 알맞은 때입니다.');
    if (warn.length) L.push(warn.join('·') + '에는 서두른 결정보다 한 번 더 확인하는 쪽이 낫습니다.');
    L.push('');

    /* ── 3 ───────────────────────────────────────────── */
    L.push('3. 반복적으로 주의해야 할 나의 행동 패턴');
    L.push(stemKey ? (ganKo(stemKey) + '(' + stemKey + ') 일간의 힘은 ' + stem.strength + '입니다. 그 대신 ' + stem.shadow + '.') : '');
    if (overEl) {
      L.push(charWord + '에 ' + overEl + ' 기운이 ' + strongN + '자로 두드러집니다. 그 힘이 세지면 ' + EL[overEl].over + '.');
    }
    if (lackEl && lackEl !== overEl) {
      var hid = false;
      var boxes = [];
      if (s.pillars) ['year', 'month', 'day', 'time'].forEach(function (k) { if (s.pillars[k] && s.pillars[k].zhi) boxes.push(s.pillars[k].zhi); });
      boxes.forEach(function (z) { if (hiddenEls(z).indexOf(lackEl) >= 0) hid = true; });
      if (weakN === 0 && hid) {
        L.push('반대로 ' + lackEl + '의 결은 겉으로 드러나지 않고 지장간에 조용히 숨어 있습니다. 그 자리가 비면 ' + EL[lackEl].lack + '. 겉으로 안 보인다고 없는 것이 아니라, 꺼내 쓰는 연습이 필요한 자리입니다.');
      } else {
        L.push('반대로 ' + lackEl + '의 결은 ' + weakN + '자로 담백한 편입니다. 그 자리가 비면 ' + EL[lackEl].lack + '. 억지로 채우기보다 ' + EL[lackEl].fill + '부터 해 보시면 균형이 편해집니다.');
      }
    }
    L.push('이 패턴은 ' + rel.rise + ' 특히 올라옵니다. 그 순간에 한 번만 멈춰 보면 같은 자리를 되풀이하지 않습니다.');
    L.push('');

    /* ── 4 ───────────────────────────────────────────── */
    L.push('4. 2027년을 위한 실천 조언 3가지');
    var acts = [];
    function add(x) { if (x && acts.indexOf(x) < 0 && acts.length < 3) acts.push(x); }
    if (lackEl) add(EL[lackEl].fill);
    add(stem.fix);
    add(area.act);
    add(rel.act);
    var marks = ['①', '②', '③'];
    acts.forEach(function (a, i) { L.push(marks[i] + ' ' + a + '.'); });
    L.push('셋 다 크게 바꾸는 일이 아닙니다. 한 가지만 골라 3주 해 보시면 됩니다.');
    L.push('');

    /* ── 5 ───────────────────────────────────────────── */
    L.push('5. 윤이세가 전하는 개인 맞춤 응원 메시지');
    L.push(name + '의 사주는 ' + stem.img + '입니다. ' + stem.cheer);
    var close = relKey === 'chung' ? '2027년은 판이 한 번 바뀌는 해입니다. 바뀌는 자리에서 흔들리지 않으면, 남는 것은 생각보다 큽니다.'
      : relKey === 'hap' ? '2027년은 사람이 이어 주는 해입니다. 먼저 손을 내미는 그 한 번이 한 해의 방향을 바꿉니다.'
        : relKey === 'hyeong' ? '2027년은 점검하는 사람이 앞서 가는 해입니다. 서두르지 않으면 오히려 빠릅니다.'
          : '2027년은 쌓는 해입니다. 눈에 띄지 않아도 한 해 끝에 남는 것이 분명 있습니다.';
    L.push(close);
    L.push('가이드는 정해진 미래를 말하는 글이 아닙니다. 2027년의 흐름을 조금 더 편하게 타기 위한 참고로 읽어 주세요. 궁금한 점은 카카오톡으로 남겨 주시면 이어서 답해 드리겠습니다.');
    L.push('');
    L.push('— 윤이세');

    return L.filter(function (x) { return x !== null && x !== undefined; }).join('\n');
  }

