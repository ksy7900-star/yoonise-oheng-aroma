    { 목: 0.6, 화: 0.75, 토: 0.9, 금: 1.4, 수: 1.2 },  // 가을 — 금왕 수상 목사 화수 토휴
    { 목: 1.2, 화: 0.6, 토: 0.75, 금: 0.9, 수: 1.4 },  // 겨울 — 수왕 목상 화사 토수 금휴
    { 목: 0.75, 화: 0.9, 토: 1.4, 금: 1.2, 수: 0.6 }   // 환절기(진술축미) — 토왕 금상 목수 화휴 수사
