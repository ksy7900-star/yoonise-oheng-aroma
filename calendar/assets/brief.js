  function titlePool(kind, group) {
    var all = TB_HEAD[kind] || TB_HEAD.calm;
    var out = [];
    for (var i = 0; i < all.length; i++) {
      if (!all[i].g || all[i].g === group) out.push(all[i]);
    }
    return out.length ? out : all;
  }

  /** 날짜 하나의 선택 — 사주 지문·십신·오행 개수·날짜로 고르고, 고른 자리를 기억한다 */
  function plan(ctx, pick) {
    var g = groupOf(ctx.tg);
    var b = bucketOf(ctx.counts ? (ctx.counts[ctx.stemEl] || 0) : 0);
    var tone = BR_TONES[(ctx.dayNo + (ctx.toneSeed | 0)) % 6];
    var rec = {};
    rec.head = pick('head:' + ctx.kind + ':' + g, titlePool(ctx.kind, g), ctx.dayNo);
    rec.open = pick('open:' + ctx.kind, BR_OPEN[ctx.kind] || BR_OPEN.calm, ctx.dayNo);
    if (ctx.kind !== 'calm') rec.why = pick('why:' + ctx.kind, BR_WHY[ctx.kind] || [], ctx.dayNo);
    rec.tg = pick('tg:' + ctx.tg, TG_SENT[ctx.tg] || TG_SENT['비견'], ctx.dayNo);
    rec.sup = pick('sup:' + g + ':' + b, (SUP_SENT[g] || SUP_SENT['비겁'])[b], ctx.dayNo);
    rec.br = pick('br:' + ctx.branchTg, BR_BRANCH[ctx.branchTg] || BR_BRANCH['비견'], ctx.dayNo);
    rec.tone = tone;
    rec.close = pick('close:' + tone, BR_CLOSE[tone] || BR_CLOSE.quiet, ctx.dayNo);
    return rec;
  }

