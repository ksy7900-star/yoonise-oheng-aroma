  /** 문장에 금지 표현이 있으면 이유, 없으면 '' */
  function bannedIn(s) {
    var t = String(s || '');
    for (var i = 0; i < BANNED.length; i++) if (BANNED[i].test ? BANNED[i].test(t) : BANNED[i].re.test(t)) return BANNED[i].why;
    return '';
  }

  /** 풀에서 걸리지 않는 첫 자리 — 다 걸리면 -1 (그 문장은 빼고 내보낸다) */
  function safeIndex(pool, start) {
    var n = pool ? pool.length : 0;
    for (var j = 0; j < n; j++) {
      var i = (((start | 0) + j) % n + n) % n;
      if (!bannedIn(pool[i])) return i;
    }
    return -1;
  }

  /** 다 만든 브리핑을 내보내기 전에 훑는다 — 제목·본문·조언이 서로 어긋나는지 포함 */
  function verify(head, sentences, ctx) {
    var body = [], i, probs = [], why;
    for (i = 0; i < (sentences || []).length; i++) if (sentences[i]) body.push(String(sentences[i]));
    var joined = body.join(' ');
    if (!head) probs.push('제목 없음');
    if (String(head).length > 36) probs.push('제목 김 ' + String(head).length);
    why = bannedIn(head + ' ' + joined);
    if (why) probs.push(why);
    if (body.length < 4 || body.length > 5) probs.push('문장 수 ' + body.length);
    if (joined.length < 90 || joined.length > 240) probs.push('분량 ' + joined.length);
    /* 한 브리핑 안에서 '오늘은'으로 시작하는 문장은 하나뿐이어야 한다 */
    var todayStarts = 0;
    for (i = 0; i < body.length; i++) if (body[i].indexOf('오늘은') === 0) todayStarts++;
    if (todayStarts > 1) probs.push("'오늘은' 중복 시작");
    /* 같은 문장이 두 번 나오면 한 브리핑이 아니라 틀로 보인다 */
    for (i = 0; i < body.length; i++) if (body.indexOf(body[i]) !== i) { probs.push('같은 문장 반복'); break; }
    /* 부딪히는 날에 '바로 결정하라'는 조언은 없다 */
    var k = (ctx && ctx.kind) || '';
    var warnDay = (k === 'chung' || k === 'hyeong' || k === 'hae');
    var todo = body.length >= 2 ? body[body.length - 2] : '';
    if (warnDay && /(바로|당장|즉시)\s*(결정|정하|답|보내|사)/.test(todo)) probs.push('조언이 그날 결에 어긋남');
    return { ok: !probs.length, problems: probs, len: joined.length, sentences: body.length };
  }

  /** 날짜 하나의 선택 — 사주 지문·십신·실질 분포·날짜로 고르고, 고른 자리를 기억한다.
      고른 자리는 모두 같은 묶음(오늘의 주제) 안에 있어, 문장끼리 주제가 갈리지 않는다. */
  function plan(ctx, pick) {
    var st = strengthOf(ctx);
    var b = fitOf(st, ctx.stemEl);
    var tg = TB_STORY[ctx.tg] ? ctx.tg : '비견';
    var S = storyOf(tg, b);
    var k = meetKindOf(ctx);
    var rec = { tg: tg, b: b, k: k };
    rec.tA = pick('tA:' + k, TITLE_A[k] || TITLE_A.calm, ctx.dayNo);
    rec.tB = pick('tB:' + tg + ':' + b, titleBOf(tg, b), ctx.dayNo);
    rec.l = pick('l:' + tg + ':' + b, S.l, ctx.dayNo);
    rec.s = pick('s:' + tg + ':' + b, S.s, ctx.dayNo);
    rec.d = pick('d:' + tg + ':' + b, S.d, ctx.dayNo);
    rec.c = pick('c:' + tg + ':' + b, S.c, ctx.dayNo);
    rec.z = pick('z:' + tg, ZARI[tg] || ZARI['비견'], ctx.dayNo);
    if (k === 'calm') rec.st = pick('st:' + b, STRENGTH[b] || STRENGTH.mid, ctx.dayNo);
    else rec.tail = pick('tail:' + k, TAIL[k], ctx.dayNo);
    return rec;
  }

  /** 제목 한 줄 + 본문 5문장 — 고른 자리(rec)를 한 사람의 상담 글로 펼친다.
      차례는 늘 하나다: 첫 문장 → 명리 한 줄 → 오늘 상황 → 할 일 → 맺음.
      다섯 문장이 모두 같은 주제를 말하므로 제목부터 마지막 문장까지 이어진다. */
  function render(ctx, rec) {
    rec = rec || plan(ctx, function (key, pool, salt) { return 0; });
    var st = strengthOf(ctx);
    var b = fitOf(st, ctx.stemEl);
    var tg = (rec.tg && TB_STORY[rec.tg]) ? rec.tg : (TB_STORY[ctx.tg] ? ctx.tg : '비견');
    var S = storyOf(tg, b);
    var k = rec.k || meetKindOf(ctx);
    var A = TITLE_A[k] || TITLE_A.calm, B = titleBOf(tg, b);
    var head = String(A[rec.tA] || A[0]) + ' ' + String(B[rec.tB] || B[0]);
    var lead = String(S.l[rec.l] || S.l[0]).replace('@', ctx.who || '');
    var Z = ZARI[tg] || ZARI['비견'];
    var zari = String(Z[rec.z] || Z[0]);
    var tail = (k === 'calm')
      ? String((STRENGTH[b] || STRENGTH.mid)[rec.st | 0] || STRENGTH.mid[0])
      : String((TAIL[k] || TAIL.chung)[rec.tail | 0] || TAIL.chung[0]);
    var basis = '오늘은 ' + zari + '가 들어오는데, ' + tail;
    var scene = String(S.s[rec.s] || S.s[0]);
    var todo = String(S.d[rec.d] || S.d[0]);
    var close = String(S.c[rec.c] || S.c[0]);
    /* 같은 문장이 한 브리핑 안에서 두 번 나오지 않게 — 맺음말을 한 칸씩 밀어 본다 */
    var used = [lead, basis, scene, todo];
    for (var ck = 1; ck < S.c.length && used.indexOf(close) >= 0; ck++) {
      var cand = S.c[((rec.c | 0) + ck) % S.c.length];
      if (used.indexOf(cand) < 0) { close = cand; break; }
    }
    var sentences = [lead, basis, scene, todo, close].filter(Boolean);
    return { head: head, sentences: sentences };
  }

