-- ────────────────────────────────────────────────────────────
-- ① 혜택 규칙 — 관리자 「회원 혜택 관리」 탭이 읽고 쓰는 표
--    trigger_kind : referral(친구 초대) | insta(인스타그램 인증)
--    stage        : 초대 인원 칸(1·3·5·7). insta 는 0
--    benefit_kind : coupon(상담 할인권) | burn(액운 태우기 추가 이용권)
-- ────────────────────────────────────────────────────────────
create table if not exists public.member_benefit_rules (
  id           bigint generated by default as identity primary key,
  trigger_kind text not null default 'referral',
  stage        int  not null default 0,
  sort         int  not null default 0,
  benefit_kind text not null default 'coupon',
  title        text not null default '',
  subtitle     text not null default '',
  coupon_kind  text,                                    -- amount | percent
  coupon_value int  not null default 0,
  applies_to   text[] not null default array['onepoint','signature']::text[],
  burn_count   int  not null default 0,
  valid_months int  not null default 6,
  active       boolean not null default true,
  updated_at   timestamptz not null default now(),
  unique (trigger_kind, stage)
);

