-- ────────────────────────────────────────────────────────────
-- ⑧ 혜택 자동 지급 — 정식 회원의 초대 인원을 세어 넘어선 칸을 한 번만 발급
--    · attach_referrer / my_referral_bonus / member_sync 어디서 불려도 결과가 같다
-- ────────────────────────────────────────────────────────────
create or replace function public.grant_member_benefits(p_user uuid, p_client text default null)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_catalog
as $$
declare
  v_client   text := nullif(btrim(coalesce(p_client, '')), '');
  v_member   boolean := false;
  v_count    int := 0;
  r          record;
  v_today    date := (now() at time zone 'Asia/Seoul')::date;
  v_prices   jsonb := public.member_list_prices();
  v_exp      date;
  v_id       bigint;
  v_granted  jsonb := '[]'::jsonb;
begin
  if p_user is null then return jsonb_build_object('ok', true, 'granted', '[]'::jsonb); end if;

  select coalesce(paid_tier in ('pass', 'allinone', 'diary'), false)
    into v_member
    from public.profiles where id = p_user;
  if v_member is not true then
    return jsonb_build_object('ok', true, 'granted', '[]'::jsonb);
  end if;

  perform pg_advisory_xact_lock(hashtext('member_benefit:' || p_user::text));

  -- 발급 때 알게 된 기기 키를 비어 있는 발급권에 채워 둔다(다른 기기에서도 보이게)
  if v_client is not null then
    update public.member_coupons
       set owner_client = v_client
     where owner_user = p_user and owner_client is null;
    update public.member_burn_credits
       set owner_client = v_client
     where owner_user = p_user and owner_client is null;
  end if;

  select count(*) into v_count from public.referrals where referrer_id = p_user;

  for r in select * from public.member_benefit_rules
            where active and trigger_kind = 'referral' and stage > 0
            order by stage
  loop
    continue when v_count < r.stage;
    v_exp := v_today + make_interval(months => greatest(coalesce(r.valid_months, 6), 1));

    if r.benefit_kind = 'coupon' and r.coupon_kind in ('amount', 'percent') and coalesce(r.coupon_value, 0) > 0 then
      insert into public.member_coupons
        (grant_key, owner_user, owner_client, source, stage, kind, value, applies_to, title, list_price, valid_months, expires_at)
      values
        ('u:' || p_user::text || '|referral|' || r.stage::text,
         p_user, v_client, 'referral', r.stage, r.coupon_kind, r.coupon_value,
         coalesce(r.applies_to, array['onepoint','signature']::text[]), r.title, v_prices,
         greatest(coalesce(r.valid_months, 6), 1), v_exp)
      on conflict (grant_key) do nothing
      returning id into v_id;
      if v_id is not null then
        v_granted := v_granted || jsonb_build_object(
          'kind', 'coupon', 'id', v_id, 'stage', r.stage, 'title', r.title,
          'coupon_kind', r.coupon_kind, 'value', r.coupon_value,
          'expires_at', to_char(v_exp, 'YYYY-MM-DD'));
      end if;
    end if;

    if r.benefit_kind = 'burn' and coalesce(r.burn_count, 0) > 0 then
      insert into public.member_burn_credits
        (grant_key, owner_user, owner_client, source, total, used, expires_at, note)
      values
        ('u:' || p_user::text || '|referral|' || r.stage::text || '|burn',
         p_user, v_client, 'referral', r.burn_count, 0, v_exp, r.title)
      on conflict (grant_key) do nothing
      returning id into v_id;
      if v_id is not null then
        v_granted := v_granted || jsonb_build_object(
          'kind', 'burn', 'id', v_id, 'stage', r.stage, 'title', r.title,
          'count', r.burn_count, 'expires_at', to_char(v_exp, 'YYYY-MM-DD'));
      end if;
    end if;
  end loop;

  return jsonb_build_object('ok', true, 'granted', v_granted);
end $$;
revoke all on function public.grant_member_benefits(uuid, text) from public;
grant execute on function public.grant_member_benefits(uuid, text) to service_role, authenticated;

-- ────────────────────────────────────────────────────────────
-- ⑨ 회원 혜택 현황 — 로그인(계정) 또는 이 기기(client_uid)로 본다
-- ────────────────────────────────────────────────────────────
create or replace function public.member_status(p_client_uid text default null)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_catalog
as $$
declare
  v_me     uuid := auth.uid();
  v_client text := nullif(btrim(coalesce(p_client_uid, '')), '');
  v_today  date := (now() at time zone 'Asia/Seoul')::date;
  v_member boolean := false;
  v_refs   int := 0;
  v_paid   int := 0;
  v_coupons jsonb := '[]'::jsonb;
  v_burn   jsonb := jsonb_build_object('total', 0, 'used', 0, 'remaining', 0);
  v_news   jsonb := '[]'::jsonb;
  v_insta  jsonb := null;
  v_stages jsonb := '[]'::jsonb;
  v_next   jsonb := null;
  r        record;
  all_prices jsonb := public.member_list_prices();
begin
  if v_client is not null and (length(v_client) < 8 or length(v_client) > 80) then
    v_client := null;
  end if;

  -- 이 기기·이 계정이 정식 회원인가 (로그인했으면 회원 DB 등급도 함께 본다)
  select coalesce(paid_tier in ('pass', 'allinone', 'diary'), false)
    into v_member from public.profiles where id = v_me;
  v_member := coalesce(v_member, false);

  if v_me is not null then
    select count(*) into v_refs from public.referrals where referrer_id = v_me;
    perform public.grant_member_benefits(v_me, v_client);
  end if;

  -- 이 기기에서 받은 발급권도 있다면 회원으로 본다(결제 후 코드로 연 기기)
  if not v_member and v_client is not null then
    v_member := exists (select 1 from public.member_coupons where owner_client = v_client and revoked_at is null)
             or exists (select 1 from public.member_burn_credits where owner_client = v_client);
  end if;

  -- 할인권 — 사용 가능 / 사용 완료 / 만료
  select coalesce(jsonb_agg(jsonb_build_object(
           'id', c.id, 'title', c.title, 'kind', c.kind, 'value', c.value,
           'applies_to', to_jsonb(c.applies_to), 'source', c.source, 'stage', c.stage,
           'issued_at', to_char(c.issued_at at time zone 'Asia/Seoul', 'YYYY-MM-DD'),
           'expires_at', to_char(c.expires_at, 'YYYY-MM-DD'),
           'used_at', case when c.used_at is null then null else to_char(c.used_at at time zone 'Asia/Seoul', 'YYYY-MM-DD') end,
           'status', case when c.revoked_at is not null then 'revoked'
                          when c.used_at is not null then 'used'
                          when c.expires_at < v_today then 'expired'
                          else 'usable' end,
           'usable', (c.revoked_at is null and c.used_at is null and c.expires_at >= v_today)
         ) order by c.issued_at desc, c.id desc), '[]'::jsonb)
    into v_coupons
    from public.member_coupons c
   where (v_me is not null and c.owner_user = v_me)
      or (v_client is not null and c.owner_client = v_client);

  -- 액운 태우기 추가 이용권 — 만료되지 않은 총/사용/남음
  select jsonb_build_object(
           'total', coalesce(sum(b.total), 0),
           'used', coalesce(sum(b.used), 0),
           'remaining', coalesce(sum(greatest(b.total - b.used, 0)), 0))
    into v_burn
    from public.member_burn_credits b
   where ((v_me is not null and b.owner_user = v_me)
       or (v_client is not null and b.owner_client = v_client))
     and (b.expires_at is null or b.expires_at >= v_today);

  -- 아직 보지 못한 지급 알림 (다음 접속 시 1회)
  select coalesce(jsonb_agg(n), '[]'::jsonb) into v_news
    from (
      select jsonb_build_object('kind', 'coupon', 'id', c.id, 'title', c.title) as n
        from public.member_coupons c
       where ((v_me is not null and c.owner_user = v_me) or (v_client is not null and c.owner_client = v_client))
         and c.seen_at is null and c.revoked_at is null
      union all
      select jsonb_build_object('kind', 'burn', 'id', b.id, 'title', coalesce(b.note, '액운 태우기 추가 이용권') || ' ' || b.total || '회')
        from public.member_burn_credits b
       where ((v_me is not null and b.owner_user = v_me) or (v_client is not null and b.owner_client = v_client))
         and b.seen_at is null
    ) s;

  -- 인스타그램 인증 상태
  select jsonb_build_object('status', i.status, 'at', to_char(i.created_at at time zone 'Asia/Seoul', 'YYYY-MM-DD'))
    into v_insta
    from public.member_insta_requests i
   where (v_me is not null and i.uniq = 'u:' || v_me::text)
      or (v_client is not null and i.uniq = 'c:' || v_client)
   order by i.created_at desc limit 1;

  -- 다음 혜택까지 남은 인원
  for r in select * from public.member_benefit_rules
            where active and trigger_kind = 'referral' and stage > 0
            order by stage
  loop
    v_stages := v_stages || jsonb_build_object(
      'stage', r.stage, 'achieved', v_refs >= r.stage,
      'remaining', greatest(r.stage - v_refs, 0), 'title', r.title,
      'benefit', r.benefit_kind);
    if v_next is null and v_refs < r.stage then
      v_next := jsonb_build_object('stage', r.stage, 'remaining', r.stage - v_refs, 'title', r.title);
    end if;
  end loop;

  return jsonb_build_object(
    'ok', true,
    'member', v_member,
    'referrals', v_refs,
    'paid', coalesce((select paid_tier in ('pass','allinone','diary') from public.profiles where id = v_me), false),
    'coupons', v_coupons,
    'burn', v_burn,
    'news', v_news,
    'insta', v_insta,
    'stages', v_stages,
    'next', v_next,
    'products', all_prices
  );
end $$;
revoke all on function public.member_status(text) from public;
grant execute on function public.member_status(text) to anon, authenticated;

-- 받은 알림을 '봤다'고 표시 — 다음 접속에 또 뜨지 않게
create or replace function public.member_seen(p_coupon_ids bigint[] default null, p_burn_ids bigint[] default null)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_catalog
as $$
declare
  v_me     uuid := auth.uid();
  v_client text := nullif(btrim(coalesce(current_setting('request.headers', true), '')), '');
begin
  if p_coupon_ids is not null then
    update public.member_coupons
       set seen_at = now()
     where id = any(p_coupon_ids) and seen_at is null
       and (v_me is null or owner_user = v_me or owner_user is null);
  end if;
  if p_burn_ids is not null then
    update public.member_burn_credits
       set seen_at = now()
     where id = any(p_burn_ids) and seen_at is null
       and (v_me is null or owner_user = v_me or owner_user is null);
  end if;
  return jsonb_build_object('ok', true);
end $$;
