-- ────────────────────────────────────────────────────────────
-- ⑩ 액운 태우기 추가 이용권 차감 — 1회 쓸 때마다 1장(동시 호출에도 초과 없음)
-- ────────────────────────────────────────────────────────────
create or replace function public.member_burn_use(p_client_uid text default null)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_catalog
as $$
declare
  v_me     uuid := auth.uid();
  v_client text := nullif(btrim(coalesce(p_client_uid, '')), '');
  v_today  date := (now() at time zone 'Asia/Seoul')::date;
  b        public.member_burn_credits;
  v_key    text;
begin
  if v_client is null and v_me is null then
    return jsonb_build_object('ok', false, 'reason', 'no_identity', 'remaining', 0);
  end if;
  v_key := coalesce('u:' || v_me::text, 'c:' || v_client);
  perform pg_advisory_xact_lock(hashtext('member_burn:' || v_key));

  select * into b from public.member_burn_credits
   where ((v_me is not null and owner_user = v_me)
       or (v_client is not null and owner_client = v_client))
     and used < total
     and (expires_at is null or expires_at >= v_today)
   order by granted_at, id
   limit 1
   for update;

  if b.id is null then
    return jsonb_build_object('ok', false, 'reason', 'none',
      'remaining', coalesce((select sum(greatest(total - used, 0)) from public.member_burn_credits
                              where ((v_me is not null and owner_user = v_me)
                                  or (v_client is not null and owner_client = v_client))
                                and (expires_at is null or expires_at >= v_today)), 0));
  end if;

  update public.member_burn_credits set used = used + 1 where id = b.id;

  return jsonb_build_object('ok', true, 'id', b.id,
    'remaining', coalesce((select sum(greatest(total - used, 0)) from public.member_burn_credits
                            where ((v_me is not null and owner_user = v_me)
                                or (v_client is not null and owner_client = v_client))
                              and (expires_at is null or expires_at >= v_today)), 0),
    'total', b.total, 'used', b.used + 1);
end $$;
revoke all on function public.member_burn_use(text) from public;
grant execute on function public.member_burn_use(text) to anon, authenticated;

