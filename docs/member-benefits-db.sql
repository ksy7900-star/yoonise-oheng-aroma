--     재배포 없이 고객 화면과 이후 지급에 바로 반영된다. 이미 발급된 할인권은 발급 당시
--     조건(금액·할인율·적용상품·만료일)을 스냅샷으로 간직한다.
--   · 상담 할인권: 1회용 · 발급일 +6개월 · 상담 1건당 1장(중복·합산 불가) · 계정당 최초 1회 발급.
--   · 결제 취소·실패 시 할인권은 소멸하지 않는다(사용 완료를 되돌린다).
